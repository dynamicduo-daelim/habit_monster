def END(k, t, d, hearts=None, label=None, nxt=None):
    e = {'k': k, 't': t, 'd': d}
    if hearts:
        e['hearts'] = hearts
        e['hearts_label'] = label
    if nxt:
        e['next'] = {'k': nxt[0], 't': nxt[1], 'd': nxt[2]}
    return e


def SP_END(who, ep, nxt, last=''):
    """종 화 끝 카드. who = (이름, 1 · 2화는 '와/과' 붙인 이름, 3화는 '이/가' 붙인 이름)."""
    name, with_ = who
    if ep == 1:
        return END('이야기가 열린 때', f'{with_} 친해진 사이가 됐어요', '호감도 4 이상이면 1화가 열려요.',
                   4, '호감도 친해진 사이', ('다음 이야기', *nxt))
    if ep == 2:
        return END('이야기가 열린 때', f'{with_} 단짝이 됐어요', '호감도 7 이상이면 2화가 열려요.',
                   5, '호감도 단짝', ('다음 이야기', *nxt))
    return END('이야기가 열린 때', f'{with_} 1차 진화했어요',
               f'Lv.10이 되면 3화가 열려요. {name} 이야기는 여기까지예요.', nxt=('다음 이야기', *nxt))


