def END(k, t, d, hearts=None, label=None, nxt=None):
    e = {'k': k, 't': t, 'd': d}
    if hearts:
        e['hearts'] = hearts
        e['hearts_label'] = label
    if nxt:
        e['next'] = {'k': nxt[0], 't': nxt[1], 'd': nxt[2]}
    return e


def SP_END(who, ep, nxt, last=''):
    """종 화 끝 카드. who = (이름, 1 · 2화는 '와/과' 붙인 이름, 3화는 '이/가' 붙인 이름)."""
    name, with_ = who
